        function sendToWhatsapp() {
            const phoneNumber = "6285161180441";
            
            // Ambil nilai dari form
            const nama = document.getElementById('formNama').value;
            const lokasi = document.getElementById('formLokasi').value;
            const kamar = document.getElementById('formKamar').value;
        
            // Validasi sederhana agar tidak mengirim pesan kosong
            if (nama === "" || lokasi === "") {
                alert("Mohon lengkapi Nama dan Lokasi Properti Anda.");
                return;
            }
        
            // Susun pesan (gunakan \n untuk baris baru)
            const message = `Halo Living Kost,\n\nSaya ingin mendapatkan informasi mengenai kerjasama kost.\n\n` +
                            `*Nama:* ${nama}\n` +
                            `*Lokasi:* ${lokasi}\n` +
                            `*Jumlah Kamar:* ${kamar}\n\n` +
                            `Mohon informasinya mengenai ketersediaan dan promonya.`;
        
            // Encode URL agar karakter spesial dan baris baru terbaca
            const waUrl = `https://wa.me/${phoneNumber}?text=${encodeURIComponent(message)}`;
        
            // Buka WhatsApp di tab baru
            window.open(waUrl, '_blank');
        }
